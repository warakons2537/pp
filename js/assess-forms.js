export const COMP_LV = ['ปรับปรุง', 'พอใช้', 'ดี', 'ดีเยี่ยม'];

// ผลรายด้าน: ฐานนิยมของคะแนน ถ้าซ้ำเท่ากันใช้ค่าต่ำสุด ไม่มีค่าซ้ำใช้ค่าต่ำสุด
// (เหมือน IFERROR(MIN(MODE.MULT(E:I)),MIN(E:I)) ในไฟล์เดิม) · แปลผลจากคะแนนรวม: 0 ไม่ผ่าน · ≥13 ดีเยี่ยม · ≥9 ดี · อื่น ๆ ผ่าน
export function compResult(comp, get) {
  const vals = comp.items.map((_, i) => num(get(`${comp.no}.${i + 1}`))).filter((v) => v !== null);
  const sum = vals.reduce((s, v) => s + v, 0);
  let level = 0;
  if (vals.length) {
    const cnt = new Map(); vals.forEach((v) => cnt.set(v, (cnt.get(v) || 0) + 1));
    const top = Math.max(...cnt.values());
    level = Math.min(...[...cnt].filter(([, n]) => n === top).map(([v]) => v));
  }
  const label = sum === 0 ? 'ไม่ผ่าน' : sum > 12.1 ? 'ดีเยี่ยม' : sum >= 9 ? 'ดี' : 'ผ่าน';
  return { sum, level, label, filled: vals.length, total: comp.items.length };
}

// สรุปภาพรวม: รวมระดับ 5 ด้าน (เต็ม 15) · 0 ปรับปรุง · ≥75% ดีเยี่ยม · ≥40% ดี · อื่น ๆ พอใช้
export function compOverall(get) {
  const per = COMPETENCIES.map((c) => compResult(c, get));
  const sum = per.reduce((s, r) => s + r.level, 0);
  const pct = (sum * 100) / 15;
  const label = sum === 0 ? 'ปรับปรุง' : pct >= 75 ? 'ดีเยี่ยม' : pct >= 40 ? 'ดี' : 'พอใช้';
  return { per, sum, pct, label, level: COMP_LV.indexOf(label), filled: per.reduce((s, r) => s + r.filled, 0), total: 25 };
}

