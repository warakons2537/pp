export const SUBS = TRAITS.flatMap((t) => t.subs.map((s) => ({ ...s, trait: t.no, traitName: t.name, codes: s.items.map((_, i) => `${s.code}.${i + 1}`) })));
export const traitCodes = (t) => t.subs.flatMap((s) => s.items.map((_, i) => `${s.code}.${i + 1}`));

const num = (v) => (v === null || v === undefined || v === '' ? null : Number(v));

// ผลรายตัวชี้วัด จากคะแนนรวม (ช่องว่างนับเป็น 0 เหมือน Excel)
export function subResult(sub, get) {
  const vals = sub.items.map((_, i) => num(get(`${sub.code}.${i + 1}`)));
  const filled = vals.filter((v) => v !== null).length;
  const sum = vals.reduce((s, v) => s + (v || 0), 0);
  const [ex, good, pass] = sub.cut;
  const label = sum > ex ? 'ดีเยี่ยม' : sum >= good ? 'ดี' : sum >= pass ? 'ผ่าน' : 'ไม่ผ่าน';
  return { sum, avg: sum / sub.items.length, label, filled, total: sub.items.length };
}

// ระดับจากค่าเฉลี่ย 0–3 (แบบสรุปผล): ดีเยี่ยม > 2.5 · ดี 1.5–2.5 · ผ่าน 1–<1.5 · ไม่ผ่าน < 1
export const levelOfAvg = (a) => (a > 2.5 ? 3 : a >= 1.5 ? 2 : a >= 1 ? 1 : 0);

// ผลรายคุณลักษณะ: คะแนนรวมทุกพฤติกรรมของข้อนั้น ÷ จำนวนพฤติกรรม (เช่น ข้อ 1 ÷ 11)
export function traitResult(trait, get) {
  const codes = traitCodes(trait);
  const vals = codes.map((c) => num(get(c)));
  const filled = vals.filter((v) => v !== null).length;
  const avg = vals.reduce((s, v) => s + (v || 0), 0) / codes.length;
  return { avg, level: levelOfAvg(avg), filled, total: codes.length };
}

export function traitOverall(get) {
  const per = TRAITS.map((t) => traitResult(t, get));
  const sum = per.reduce((s, r) => s + r.avg, 0);
  const avg = sum / TRAITS.length;
  const filled = per.reduce((s, r) => s + r.filled, 0);
  return { per, sum, avg, level: levelOfAvg(avg), filled, total: per.reduce((s, r) => s + r.total, 0) };
}

