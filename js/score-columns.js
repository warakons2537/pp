//  ช่องคะแนนเริ่มที่ BZ (คอลัมน์ 78) แล้วเรียงไปทางขวา 12 ช่อง (BZ–CK) ตามใบที่โรงเรียนพิมพ์
//  ชิ้นที่ 13 ขึ้นไป (เฉพาะแผ่นเต็มวิชาที่ 1–10) ต่อไปที่ AP (คอลัมน์ 42) ·
//  แผ่นวิชาที่ 11+ ซ่อนคอลัมน์ AP–BY จึงมีได้ 12 ช่อง
// =====================================================================
export const SCORE_FIRST_COL = 78;       // BZ
export const SCORE_EXTRA_COL = 42;       // AP
export const SCORE_MAIN = 12;            // BZ–CK
export const scoreColIndex = (k) => (k < SCORE_MAIN ? SCORE_FIRST_COL + k : SCORE_EXTRA_COL + (k - SCORE_MAIN));
